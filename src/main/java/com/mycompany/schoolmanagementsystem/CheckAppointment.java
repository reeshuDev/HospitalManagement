    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        String patientId=pid.getText();
        int patientid=Integer.parseInt(patientId);
        try{
            DefaultTableModel model = (DefaultTableModel)Table.getModel();
            //load Driver
            Class.forName("com.mysql.cj.jdbc.Driver");
            //Create Connection
            Connection con =DriverManager.getConnection("jdbc:mysql://localhost:3306/Hospital","root","#Dh8666@");
            
            PreparedStatement pstmt = con.prepareStatement("SELECT * FROM patient WHERE id=?");
            pstmt.setString(1, patientId);
            ResultSet rs = pstmt.executeQuery();
            while(rs.next()){
                int dbPatientId = rs.getInt("id");
                String pIdStr= Integer.toString(dbPatientId);
                String pname = rs.getString("name");
                int page = rs.getInt("age");
                String pAge=Integer.toString(page);
                String dname = rs.getString("doctorName");
                String row[]={pIdStr,pname,pAge,dname};
                model.addRow(row);
            }
            con.close();
            
        }catch(Exception e){
            JOptionPane.showMessageDialog(this , e);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

